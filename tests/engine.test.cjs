// Запуск: node tests/engine.test.cjs (без зависимостей)
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const cwd=path.resolve(__dirname,'..');
const sandbox={window:{},URL,Date};vm.createContext(sandbox);
for(const f of ['js/data.js','js/engine.js'])vm.runInContext(fs.readFileSync(path.join(cwd,f),'utf8'),sandbox,{filename:f});
const D=sandbox.window.SimData,E=sandbox.window.SimEngine;
let tests=0;
function eq(a,b,label){assert.equal(a,b,label);tests++;}
for(const c of D.cases)eq(E.evaluate({value:c.value,quality:c.quality,age:c.age}),c.answer,'Case '+c.id);
eq(E.evaluate({value:1080,quality:'Good',age:10}),'ready','lower inclusive');
eq(E.evaluate({value:1140,quality:'Good',age:10}),'ready','upper inclusive');
eq(E.evaluate({value:1100,quality:'Good',age:11}),'unreliable','age 11');
eq(E.evaluate({value:1100,quality:'Good',age:-1}),'unreliable','negative age');
eq(E.evaluate({value:1100,quality:'Uncertain',age:2}),'unreliable','uncertain');
eq(E.evaluate({value:null,quality:'Bad',age:null}),'missing','missing first');
const goodSettings={checkMissing:true,checkQuality:true,checkFreshness:true,inclusiveBounds:true};
for(const c of D.cases)eq(E.evaluateCandidate({value:c.value,quality:c.quality,age:c.age},goodSettings),c.answer,'Candidate '+c.id);
const bugSettings={checkMissing:true,checkQuality:true,checkFreshness:false,inclusiveBounds:false};
assert(D.cases.some(c=>E.evaluateCandidate(c,bugSettings)!==c.answer),'default exercise must contain bugs');tests++;
const stale=E.createScenario('stale');eq(stale.status,'unreliable','initial stale');const old=stale.reading.age;E.tick(stale);eq(stale.reading.age,old+1,'frozen age increments');
const normal=E.createScenario('normal');const n=normal.history.length;E.tick(normal);eq(normal.history.length,n+1,'history grows');
const missing=E.createScenario('missing');eq(E.dataValue(missing).SourceTimestamp,null,'missing sourceTimestamp');
const bad=E.createScenario('bad');eq(E.dataValue(bad).Value,null,'bad OPC value null');
E.inject(normal,{value:1146,quality:'Good',age:2});eq(normal.status,'range','inject');eq(normal.running,false,'inject pauses');
const good=E.createScenario('normal');eq(E.dataValue(good).StatusCode,'Good','DataValue status code');eq(Boolean(E.dataValue(good).ServerTimestamp),true,'server time');

const rules2=E.rulesFor('revision');
eq(E.evaluate({value:1135,quality:'Good',age:3},rules2),'range','revision upper bound');
eq(E.evaluate({value:1100,quality:'Good',age:6},rules2),'unreliable','revision freshness');
for(const rules of [D.rules,...Object.values(D.regulations)]){
  const generated=E.testsFor(rules);
  for(const c of generated)eq(E.evaluate(c,rules),c.answer,'generated oracle '+rules.id+' '+c.id);
  eq(generated[3].value,rules.max,'generated upper boundary follows regulation');
  eq(generated[5].age,rules.maxAge+1,'generated stale age follows regulation');
}
const manual=E.createScenario('normal');E.inject(manual,{value:1100,quality:'Good',age:120});
let packet=E.dataValue(manual);
eq((Date.parse(packet.ServerTimestamp)-Date.parse(packet.SourceTimestamp))/1000,120,'120 seconds is not clipped');
E.tick(manual);packet=E.dataValue(manual);
eq((Date.parse(packet.ServerTimestamp)-Date.parse(packet.SourceTimestamp))/1000,121,'manual age and timestamp advance together');
const cycle=E.createScenario('heating-cycle');
for(let i=0;i<8;i++)E.tick(cycle);
eq(cycle.phase,'Выдержка','cycle reaches soak');eq(cycle.holdElapsed,0,'soak starts at zero elapsed seconds');
eq(cycle.status,'ready','temperature is valid before soak completes');eq(E.readiness(cycle),'Выдержка не завершена','measurement is distinct from process readiness');
for(let i=0;i<5;i++)E.tick(cycle);
eq(cycle.events[0].processDecision,'Условия выполнены','process result is journaled');
eq(cycle.events[0].holdElapsed,5,'soak evidence is journaled');
eq(cycle.holdElapsed,5,'five real simulation seconds of soak');eq(E.readiness(cycle),'Условия выполнены','soak completes');
const fault=E.createScenario('heating-fault');for(let i=0;i<10;i++)E.tick(fault);
eq(fault.status,'unreliable','fault during soak');eq(fault.holdElapsed,0,'fault resets soak');
for(let i=0;i<4;i++)E.tick(fault);
eq(fault.status,'ready','signal recovers');eq(fault.holdElapsed,0,'recovered sample starts a new soak');
for(let i=0;i<5;i++)E.tick(fault);eq(E.readiness(fault),'Условия выполнены','fresh soak after recovery');
const delayed=E.createScenario('heating-delay');for(let i=0;i<26;i++)E.tick(delayed);
eq(delayed.phase,'Передача на прокатку','transfer stage');eq(delayed.status,'range','delayed transfer cools below range');
eq(delayed.holdElapsed,0,'loss of range invalidates soak');
const batch=E.createScenario('heating-batch');for(let i=0;i<20;i++)E.tick(batch);eq(E.readiness(batch),'Партия не совпадает','wrong batch cannot pass');
E.inject(batch,{value:1100,quality:'Good',age:0});eq(E.readiness(batch),'Партия не совпадает','editing temperature cannot silently change batch identity');
const restored=E.restoreSim(JSON.parse(JSON.stringify(cycle)));
eq(restored.elapsed,cycle.elapsed,'restored clock');eq(restored.holdElapsed,cycle.holdElapsed,'restored soak');eq(restored.running,false,'reload pauses model');
const resumed=E.restoreSim(JSON.parse(JSON.stringify(fault)));E.tick(resumed);E.tick(fault);eq(resumed.reading.value,fault.reading.value,'restored trace is deterministic');
assert.throws(()=>E.restoreSim({...cycle,history:[null]}),/history point/);tests++;
assert.throws(()=>E.restoreSim({...cycle,events:[null]}),/event/);tests++;
assert.throws(()=>E.rulesFor('__proto__'),/Unknown/);tests++;
const point=(t,v,quality='Good',status='ready')=>({t,v,quality,status});
const segments=E.historySegments([point(0,1100),point(1,1101),point(2,null),point(3,1102),point(4,1103,'Bad','unreliable'),point(5,1104,'Bad','unreliable'),point(6,1105,'Good','unreliable')]);
eq(segments.length,3,'missing breaks line and quality splits line');eq(segments[0].points.length,2,'no line through gap');eq(segments[2].reliable,false,'stale good signal shown unreliable');
for(const defect of D.defects){
  const input={value:defect.id==='bounds'?D.rules.max:1100,quality:defect.id==='quality'?'Bad':'Good',age:2};
  assert.notEqual(E.evaluateDefect(input,defect.id),E.evaluate(input),'counterexample '+defect.id);tests++;
}
eq(E.evaluateDefect({value:1100,quality:'Good',age:3},'bounds'),'ready','middle does not expose boundary bug');
eq(E.correctOrder(['missing','quality','freshness','range']),true,'correct order');
eq(E.correctOrder(['missing','freshness','quality','range']),true,'equivalent data checks order');
eq(E.correctOrder(['range','quality','missing','freshness']),false,'range must be last');
eq(E.validTest({value:null,missing:false,quality:'Good',age:0,expected:'ready'}),false,'blank present value is not a missing test');
const work={caseId:'heating',parameter:{name:'Temperature',point:'Pyrometer',unit:'°C',min:1080,max:1140,maxAge:10,inclusive:true,checkMissing:true,checkQuality:true,checkFreshness:true,reaction:'Show cause'},requirements:Array.from({length:4},(_,i)=>({source:String(i+1),text:'Observable behavior'})),tests:[{value:1080,quality:'Good',age:10,expected:'ready'},{value:null,quality:'Bad',age:null,expected:'missing'},{value:1100,quality:'Good',age:11,expected:'unreliable'}]};
eq(E.assessWorkshop(work).readyForReview,true,'complete structured workshop');
eq(E.assessWorkshop({...work,tests:[work.tests[0],work.tests[0],work.tests[0]]}).readyForReview,false,'duplicates do not cover missing and stale');
eq(E.assessWorkshop({...work,parameter:{...work.parameter,unit:'K'}}).readyForReview,false,'wrong unit rejected');
for(const item of D.productionCases)eq(E.productionDecision(item),item.answer,'production case '+item.id);
const casting=D.productionCases.find(c=>c.id==='casting');
eq(E.studentTestResult({value:1540,quality:'Good',age:2,scope:'process',context:'original'},E.rulesFor('casting'),'casting'),'unreliable','process test reproduces bad level');
eq(E.studentTestResult({value:1540,quality:'Good',age:2,scope:'process',context:'good'},E.rulesFor('casting'),'casting'),'ready','process test repairs extra data');
const rev={requirements:['FR-02','FR-03'],max:1130,maxAge:5,explanation:'Changed upper bound and age',tests:[{value:1130,quality:'Good',age:5,expected:'ready'},{value:1135,quality:'Good',age:3,expected:'range'},{value:1100,quality:'Good',age:6,expected:'unreliable'}]};
eq(E.checkRevision(rev).ok,true,'complete revision exercise');eq(E.checkRevision({...rev,requirements:['FR-01','FR-02']}).ok,false,'wrong impacted requirements');
eq(E.checkRevision({...rev,tests:rev.tests.map(t=>({...t,expected:'ready'}))}).ok,false,'old expectations fail revision');
eq(E.checkRevision({...rev,explanation:''}).ok,false,'revision requires explanation for review');
let alarm=E.alarmTransition({active:false,acknowledged:true},'raise');alarm=E.alarmTransition(alarm,'ack');
eq(alarm.active,true,'acknowledgement does not remove cause');eq(alarm.acknowledged,true,'alarm acknowledged');
alarm=E.alarmTransition(E.alarmTransition(alarm,'raise'),'clear');eq(alarm.acknowledged,false,'clearing cause does not acknowledge');eq(alarm.active,false,'cause cleared independently');
console.log(`OK: ${tests} engine checks`);
